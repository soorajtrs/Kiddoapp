#!/usr/bin/env node
// Pre-renders every Malayalam string used in the app (letters, words, story
// pages) into a small MP3 clip using espeak-ng's own Malayalam voice, and
// writes js/ml-audio.js mapping text -> clip path.
//
// Why: browser text-to-speech depends on the device having a Malayalam
// voice installed, which most don't - so audio would be silent or an
// English misreading. Pre-rendering ships correct pronunciation inside the
// app itself, with no runtime dependency on the device's OS/browser voices.
//
// Requires espeak-ng and lame on PATH (e.g. `apt-get install espeak-ng lame`
// or `brew install espeak-ng lame`). Re-run this whenever Malayalam text in
// js/data.js changes, then commit the new/changed files under audio/ml/.

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const { execFileSync } = require('child_process');
const os = require('os');

const ROOT = path.join(__dirname, '..');
const DATA_JS = path.join(ROOT, 'js', 'data.js');
const AUDIO_DIR = path.join(ROOT, 'audio', 'ml');
const MANIFEST_JS = path.join(ROOT, 'js', 'ml-audio.js');

function loadData() {
  let src = fs.readFileSync(DATA_JS, 'utf8');
  src += '\nthis.LETTER_GROUPS = LETTER_GROUPS; this.WORD_CATEGORIES = WORD_CATEGORIES; this.STORIES = STORIES;';
  const sandbox = {};
  vm.createContext(sandbox);
  vm.runInContext(src, sandbox);
  return sandbox;
}

function collectMalayalamTexts(sandbox) {
  const items = new Set();
  Object.values(sandbox.LETTER_GROUPS).forEach(arr => arr.forEach(l => items.add(l.ch)));
  Object.values(sandbox.WORD_CATEGORIES).forEach(arr => arr.forEach(w => items.add(w.mal)));
  sandbox.STORIES.forEach(s => s.pages.forEach(p => items.add(p.mal)));
  return [...items];
}

function main() {
  fs.mkdirSync(AUDIO_DIR, { recursive: true });
  const texts = collectMalayalamTexts(loadData());
  const manifest = {};

  for (const text of texts) {
    const hash = crypto.createHash('md5').update(text, 'utf8').digest('hex').slice(0, 10);
    const mp3Path = path.join(AUDIO_DIR, `${hash}.mp3`);
    manifest[text] = `audio/ml/${hash}.mp3`;
    if (fs.existsSync(mp3Path)) continue; // already generated, skip re-synthesis

    const wavPath = path.join(os.tmpdir(), `${hash}.wav`);
    execFileSync('espeak-ng', ['-v', 'ml', '-s', '130', '-w', wavPath, text]);
    execFileSync('lame', ['-b', '32', '-q', '2', '--silent', wavPath, mp3Path]);
    fs.unlinkSync(wavPath);
  }

  const header =
    "// Auto-generated by scripts/gen-ml-audio.js - maps Malayalam text to a\n" +
    "// bundled, pre-rendered audio clip (espeak-ng 'ml' voice) shipped with the\n" +
    "// app itself, so pronunciation never depends on the device having a\n" +
    "// Malayalam voice installed.\n" +
    "const ML_AUDIO_MANIFEST = ";
  fs.writeFileSync(MANIFEST_JS, header + JSON.stringify(manifest, null, 2) + ';\n');

  console.log(`Generated/verified ${texts.length} clips -> ${path.relative(ROOT, AUDIO_DIR)}/`);
}

main();
